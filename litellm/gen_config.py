#!/usr/bin/env python3
"""Write LiteLLM's config from llama-swap's config.yaml.

Every llama-swap model and alias (listed or not) becomes a LiteLLM route to
llama-swap on 127.0.0.1:8033, so /v1/models on the gateway lists the same names.
A "*" route at the end passes any other name straight through, so a model added
to llama-swap works before this is re-run (it just isn't listed yet).

Run by litellm.service before every start; litellm-reload.path restarts the
service when config.yaml changes.
"""
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SWAP_CONFIG = HERE.parent / "config.yaml"
OUT = HERE / "config.generated.yaml"
UPSTREAM = "http://127.0.0.1:8033/v1"


def route(name: str, model: str) -> dict:
    return {"model_name": name,
            "litellm_params": {"model": f"openai/{model}", "api_base": UPSTREAM, "api_key": "none"}}


def main() -> None:
    models = yaml.safe_load(SWAP_CONFIG.read_text())["models"]
    names = []
    for key, entry in models.items():
        names.append(key)
        names += (entry or {}).get("aliases") or []
    config = {
        "model_list": [route(n, n) for n in dict.fromkeys(names)] + [route("*", "*")],
        "litellm_settings": {
            "callbacks": ["tracing.opik"],  # Opik, without embeddings (tracing.py)
            # llama-swap's servers take extra parameters (chat_template_kwargs, top_k,
            # ...); keep them, don't drop or reject them.
            "drop_params": False,
            "request_timeout": 3600,
        },
        "general_settings": {"custom_auth": "auth.user_api_key_auth"},
    }
    OUT.write_text("# Generated by gen_config.py from ../config.yaml. Don't edit.\n"
                   + yaml.safe_dump(config, sort_keys=False))


if __name__ == "__main__":
    main()
