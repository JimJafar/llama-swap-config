#!/usr/bin/env bash
# crispasr Chatterbox-Turbo TTS, run by llama-swap as `chatterbox-turbo`: the voice of
# alexa-marvin's assistant (the Wyoming bridge on Colin calls it directly) and of any
# llama-swap client. Was ~/lab/crispasr/start-tts.sh, started by hand, beside a second,
# unused copy in llama-swap; one copy since 2026-10-13.
#
# FIXED PORT 5811: the bridge calls https://marvin.akita-betelgeuse.ts.net:5811, which
# `tailscale serve --https=5811` forwards to 127.0.0.1:5811.
# MUST run from ~/lab/crispasr: the bridge sends the voice as "voices/<name>.wav",
# which crispasr resolves relative to its own cwd (absolute paths are rejected).
# Voices: voices/<name>.wav (24 kHz mono, ~20 s) + <name>.txt (its transcript).
# --i-have-rights --consent-log: crispasr clones a voice only with them.
# --no-spoken-disclaimer: without it every cloned-voice reply starts with an audible
# "This audio was generated by artificial intelligence". crispasr only honours that
# opt-out alongside --accept-marking-responsibility, i.e. the operator (Jim) takes on
# the AI-content disclosure duty. The inaudible watermark and C2PA provenance are still
# applied; only the spoken prefix is gone.
# GPU: the ZOTAC, by UUID (device numbers depend on CUDA's ordering).
cd /home/jim/lab/crispasr || exit 1
export CUDA_VISIBLE_DEVICES=GPU-af5bd53f-a1ca-d807-1ae2-7f5ef261fe1a
export LD_LIBRARY_PATH=/home/jim/lab/crispasr/crispasr-linux-x86_64-cuda13
exec ./crispasr-linux-x86_64-cuda13/crispasr \
  --server --backend chatterbox-turbo -m auto -dev 0 \
  --voice-dir "$PWD/voices" --port 5811 \
  --i-have-rights --consent-log "$PWD/consent.log" \
  --no-spoken-disclaimer --accept-marking-responsibility "$@"
